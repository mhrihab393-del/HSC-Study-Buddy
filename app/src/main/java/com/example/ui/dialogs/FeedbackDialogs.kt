                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween
                        ) {
                            Text("Time Studied", fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
