                            Text("Topic", fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                            Text(session.chapterTopic, fontSize = 12.sp, fontWeight = FontWeight.SemiBold)
                        }
                        Spacer(modifier = Modifier.height(6.dp))
